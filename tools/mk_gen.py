#!/usr/bin/env python3
"""mk_gen.py -- the kernel table of the megakernel (kernels/ie_mk.c).

Reads the KERNEL declarations of kernels/ie_kernels.c and writes a header with:
  - enum MK_<kernel>: the kernel ids of the command list;
  - device (IE_MEGA defined): struct mka_<kernel> (the parameters in kernel
    argument order: the same layout as the kernel arguments of a launch) and
    MK_DISPATCH(kid, args): a switch that calls the kernel body;
  - host: mk_names, mk_nargs, mk_argsz (the size of each parameter: 8 for a
    pointer, 4 for u32 / int / float), so the host packs the void **args of
    a launch into the same bytes.

  tools/mk_gen.py kernels/ie_kernels.c OUT.h kernel ...
"""
import re
import sys

src, out, names = sys.argv[1], sys.argv[2], sys.argv[3:]
text = open(src).read()
sizes4 = {"u32", "int", "float", "unsigned"}


def params(name):
    m = re.search(r"^KERNEL\s+" + re.escape(name) + r"\s*\(([^)]*)\)\s*\{", text, re.M)
    if not m:
        sys.exit("mk_gen: no KERNEL %s in %s" % (name, src))
    ps = []
    for p in m.group(1).split(","):
        p = " ".join(p.split())
        pm = re.match(r"(.*?)([A-Za-z_][A-Za-z0-9_]*)$", p)
        ty, nm = pm.group(1).strip(), pm.group(2)
        if "*" in ty:
            sz = 8
        elif ty.replace("const ", "") in sizes4:
            sz = 4
        else:
            sys.exit("mk_gen: %s: parameter type '%s' not handled" % (name, ty))
        ps.append((ty, nm, sz))
    return ps


ks = [(n, params(n)) for n in names]
o = ["/* Generated by tools/mk_gen.py from %s: do not edit. */" % src, "#ifndef IE_MK_GEN_H", "#define IE_MK_GEN_H"]
o.append("enum { " + ", ".join("MK_%s" % n for n, _ in ks) + ", MK_N };")
o.append("#define MK_MAXARGS %d" % max(len(p) for _, p in ks))
o.append("#ifdef IE_MEGA")
for n, ps in ks:
    o.append("struct mka_%s { %s };" % (n, " ".join("%s %s;" % (t, v) for t, v, _ in ps)))
o.append("#define MK_DISPATCH(kid, a) switch (kid) { \\")
for n, ps in ks:
    o.append("  case MK_%s: { const G struct mka_%s *p_ = (const G struct mka_%s *)(a); %s(%s); } break; \\"
             % (n, n, n, n, ", ".join("p_->%s" % v for _, v, _ in ps)))
o.append("  default: break; }")
o.append("#else")
o.append("static const char *const mk_names[MK_N] = {%s};" % ", ".join('"%s"' % n for n, _ in ks))
o.append("static const unsigned char mk_nargs[MK_N] = {%s};" % ", ".join(str(len(p)) for _, p in ks))
o.append("static const unsigned char mk_argsz[MK_N][MK_MAXARGS] = {%s};"
         % ", ".join("{%s}" % ", ".join(str(s) for _, _, s in p) for _, p in ks))
o.append("#endif")
o.append("#endif")
open(out, "w").write("\n".join(o) + "\n")
